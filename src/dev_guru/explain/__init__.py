"""Explanations grounded in the code graph: one file or symbol at four levels (``dev explain``).

The levels are a ladder, from the reader who is new to code to the one who decides what to fund:

* ``novice``: what it is and what it's for, in plain words;
* ``practitioner``: signatures, what calls it and what it calls, with the lines;
* ``principal``: where it sits in the architecture and what a change would reach;
* ``executive``: how central it is and what the risk is, in a sentence or two.

Every statement comes from the explorer view model (Ananke's graph plus the repository analysis) and carries its
evidence (``path`` and ``line``) and its basis: ``observed`` (read from the code), ``derived`` (counted from what was
observed) or ``inferred`` (a call Ananke resolved through imports). Nothing is generated by a model, so the same
code always gives the same explanation.
"""

from __future__ import annotations

import re
from collections import defaultdict, deque
from dataclasses import dataclass, field
from typing import Any

SCHEMA = "dev-guru/explanation@1"
LEVELS = ("novice", "practitioner", "principal", "executive")
COMPLEX = 10  # cyclomatic complexity at which a function is called hard to change
CENTRAL = (
    0.25  # share of files depending on one file, directly or not, at which it's called central
)


class ExplainError(ValueError):
    pass


def first_sentence(text: str) -> str:
    text = " ".join(text.strip().split())
    if not text:
        return ""
    end = re.search(r"(?<=[.!?])\s", text)
    return (text[: end.start()] if end else text)[:240]


def parameters(signature: str) -> list[str]:
    """Parameter names from ``def f(a: dict[str, int], *, b=1) -> X``; commas inside brackets don't split."""
    start = signature.find("(")
    if start < 0:
        return []
    depth, part, parts = 0, "", []
    for ch in signature[start + 1 :]:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            if depth == 0:
                break
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(part)
            part = ""
        else:
            part += ch
    parts.append(part)
    names = [p.split(":")[0].split("=")[0].strip().lstrip("*") for p in parts]
    return [n for n in names if n and n not in ("self", "cls", "/")]


def _plural(n: int, word: str, many: str | None = None) -> str:
    return f"{n} {word if n == 1 else many or word + 's'}"


def _share(n: int, total: int) -> str:
    return f"{round(100 * n / total)}%" if total else "0%"


@dataclass
class Facts:
    """Indexes over one explorer model, built once and shared by the ladder and the documentation."""

    model: dict[str, Any]
    files: dict[str, dict[str, Any]] = field(init=False)
    symbols: dict[str, dict[str, Any]] = field(init=False)
    imports: dict[str, set[str]] = field(init=False)
    importers: dict[str, set[str]] = field(init=False)
    callers: dict[str, list[dict[str, Any]]] = field(init=False)
    callees: dict[str, list[dict[str, Any]]] = field(init=False)
    bases: dict[str, list[str]] = field(init=False)
    hotspots: dict[tuple[str, str], tuple[int, int]] = field(init=False)
    in_cycle: dict[str, list[str]] = field(init=False)

    def __post_init__(self) -> None:
        m = self.model
        self.files = {f["id"]: f for f in m.get("files", [])}
        self.symbols = {s["id"]: s for s in m.get("symbols", [])}
        self.imports, self.importers = defaultdict(set), defaultdict(set)
        self.callers, self.callees = defaultdict(list), defaultdict(list)
        self.bases = defaultdict(list)
        for e in m.get("edges", []):
            if e["k"] == "imports":
                self.imports[e["s"]].add(e["t"])
                self.importers[e["t"]].add(e["s"])
            elif e["k"] == "calls":
                self.callers[e["t"]].append(e)
                self.callees[e["s"]].append(e)
            elif e["k"] == "inherits":
                self.bases[e["s"]].append(e["t"])
        self.hotspots = {}
        for row in (m.get("repository") or {}).get("hotspots", []):
            name, complexity, where = row
            path, _, line = str(where).rpartition(":")
            self.hotspots[(path, str(name))] = (
                int(complexity or 0),
                int(line) if line.isdigit() else 0,
            )
        self.in_cycle = {}
        for cycle in m.get("insights", {}).get("cycles", []):
            for fid in cycle:
                self.in_cycle[fid] = cycle

    # ---------------------------------------------------------------- lookups
    def path(self, node_id: str) -> str:
        if node_id in self.files:
            return str(self.files[node_id]["path"])
        sym = self.symbols.get(node_id)
        return str(self.files.get(sym["file"], {}).get("path", "")) if sym else ""

    def resolve(self, focus: str) -> str:
        """A file or symbol id from an id, a path, a file name or a symbol name (or ``file.py:name``)."""
        if focus in self.files or focus in self.symbols:
            return focus
        if "file:" + focus in self.files:
            return "file:" + focus
        if ":" in focus and not focus.startswith(("file:", "function:", "class:", "method:")):
            where, _, name = focus.rpartition(":")
            hits = [
                s["id"]
                for s in self.symbols.values()
                if s["name"] == name
                and (self.path(s["id"]) == where or self.path(s["id"]).endswith("/" + where))
            ]
        else:
            hits = [
                f["id"]
                for f in self.files.values()
                if f["path"].endswith("/" + focus) or f["name"] == focus
            ]
            hits += [s["id"] for s in self.symbols.values() if s["name"] == focus]
        hits = sorted(set(hits))
        if len(hits) == 1:
            return str(hits[0])
        if not hits:
            raise ExplainError(f"nothing called {focus!r} in this project")
        shown = ", ".join(hits[:5]) + (" …" if len(hits) > 5 else "")
        raise ExplainError(
            f"{focus!r} matches {len(hits)} things: {shown}. Use one of these ids, or path:name"
        )

    def reach(self, file_id: str) -> set[str]:
        """Every file that imports this one, directly or through others: what a change here can reach."""
        seen: set[str] = set()
        queue = deque([file_id])
        while queue:
            for importer in self.importers.get(queue.popleft(), ()):
                if importer not in seen and importer != file_id:
                    seen.add(importer)
                    queue.append(importer)
        return seen

    def reading_path(self, limit: int) -> list[str]:
        """Files in the order a newcomer could read them: entry points first, then what they import."""
        starts = (
            self.model.get("insights", {}).get("entry_points", [])
            or self.model.get("insights", {}).get("most_depended", [])[:1]
        )
        order: list[str] = []
        queue = deque(starts)
        while queue and len(order) < limit:
            fid = queue.popleft()
            if fid in order or fid not in self.files:
                continue
            order.append(fid)
            queue.extend(sorted(self.imports.get(fid, ())))
        return order


def _say(text: str, basis: str, *evidence: tuple[str, int]) -> dict[str, Any]:
    return {
        "text": text,
        "basis": basis,
        "evidence": [{"path": p, "line": line} for p, line in evidence if p],
    }


def _file_ladder(facts: Facts, fid: str) -> dict[str, list[dict[str, Any]]]:
    f = facts.files[fid]
    path = f["path"]
    total = len(facts.files)
    defined = [
        facts.symbols[s]
        for s in f["symbols"]
        if s in facts.symbols and "." not in facts.symbols[s]["name"]
    ]
    top = [s for s in defined if s["kind"] in ("class", "function")]
    uses = sorted(facts.imports.get(fid, ()), key=facts.path)
    used_by = sorted(facts.importers.get(fid, ()), key=facts.path)
    reach = facts.reach(fid)
    doc = first_sentence(f.get("doc", ""))
    novice = [
        _say(
            f"`{f['name']}` is a file of {_plural(f['loc'], 'line')}"
            + (
                f" in the `{f['package']}` folder."
                if f["package"] != "."
                else " at the top of the project."
            ),
            "observed",
            (path, 1),
        )
    ]
    if doc:
        novice.append(_say(f"Its own description says: “{doc}”", "observed", (path, 1)))
    if top:
        names = ", ".join(
            f"{'a class' if s['kind'] == 'class' else 'a function'} `{s['name']}`" for s in top[:6]
        )
        novice.append(
            _say(
                f"It defines {_plural(len(top), 'thing')}: {names}"
                + (", and more." if len(top) > 6 else "."),
                "observed",
                *((path, s["line"]) for s in top[:6]),
            )
        )
    if f.get("entry"):
        novice.append(
            _say("It's a starting point: running the program begins here.", "observed", (path, 1))
        )
    novice.append(
        _say(
            (
                f"It uses code from {_plural(len(uses), 'other file')} in this project"
                + f" ({', '.join('`' + facts.path(u) + '`' for u in uses[:4])}"
                + (", …)" if len(uses) > 4 else ")")
                if uses
                else "It doesn't use code from other files in this project"
            )
            + (
                f", and {_plural(len(used_by), 'file')} {'uses' if len(used_by) == 1 else 'use'} it."
                if used_by
                else ", and no other file imports it."
            ),
            "derived",
            (path, 0),
        )
    )

    practitioner = []
    for s in top[:12]:
        sig = s.get("signature") or s["name"]
        said = f"`{sig}`" + (f": {first_sentence(s['doc'])}" if s.get("doc") else "")
        practitioner.append(_say(said, "observed", (path, s["line"])))
    if uses:
        practitioner.append(
            _say(
                "Imports " + ", ".join(f"`{facts.path(u)}`" for u in uses) + ".",
                "observed",
                (path, 0),
            )
        )
    external = [m for m in f.get("external", []) if m != "__future__"]
    if external:
        practitioner.append(
            _say(
                "Outside libraries: " + ", ".join(f"`{m}`" for m in external) + ".",
                "observed",
                (path, 0),
            )
        )
    if used_by:
        practitioner.append(
            _say(
                "Imported by " + ", ".join(f"`{facts.path(u)}`" for u in used_by[:12]) + ".",
                "observed",
                *((facts.path(u), 0) for u in used_by[:12]),
            )
        )
    out_calls = sorted(
        {
            (facts.path(e["t"]), facts.symbols[e["t"]]["name"], e["line"], e["o"])
            for s in defined
            for e in facts.callees.get(s["id"], [])
            if facts.symbols[e["t"]]["file"] != fid
        }
    )
    for target_path, name, line, origin in out_calls[:8]:
        practitioner.append(
            _say(
                f"Calls `{name}` in `{target_path}`.",
                "inferred" if origin == "inferred" else "observed",
                (path, line),
            )
        )

    principal = [
        _say(
            f"{_plural(f['fan_in'], 'file')} {'imports' if f['fan_in'] == 1 else 'import'} it directly and it imports "
            f"{_plural(f['fan_out'], 'project file')}; a change here can reach {_plural(len(reach), 'file')} "
            f"({_share(len(reach), total)} of {total}).",
            "derived",
            (path, 0),
        )
    ]
    if fid in facts.in_cycle:
        others = [facts.path(o) for o in facts.in_cycle[fid] if o != fid]
        principal.append(
            _say(
                "It's in an import cycle with "
                + ", ".join(f"`{o}`" for o in others)
                + ": none of them can be changed or tested alone.",
                "derived",
                (path, 0),
                *((o, 0) for o in others),
            )
        )
    complex_here = sorted(
        (
            (c, name, line)
            for (p, name), (c, line) in facts.hotspots.items()
            if p == path and c >= COMPLEX
        ),
        reverse=True,
    )
    for c, name, line in complex_here[:4]:
        principal.append(
            _say(
                f"`{name}` has a cyclomatic complexity of {c}: hard to change safely.",
                "derived",
                (path, line),
            )
        )
    if not f["fan_in"] and not f.get("entry"):
        principal.append(
            _say(
                "Nothing in the project imports it: it's either a leaf, unused, or loaded some other way.",
                "derived",
                (path, 0),
            )
        )

    share = len(reach) / total if total else 0
    role = (
        "central: much of the project depends on it"
        if share >= CENTRAL or fid in facts.model.get("insights", {}).get("most_depended", [])[:3]
        else "an entry point"
        if f.get("entry")
        else "a leaf: little depends on it"
        if not reach
        else "a supporting part"
    )
    risks = []
    if fid in facts.in_cycle:
        risks.append("it's tangled in an import cycle")
    if complex_here:
        risks.append(_plural(len(complex_here), "function") + " in it are hard to change")
    executive = [
        _say(
            f"`{path}` is {role}. Changing it can affect {_share(len(reach), total)} of the project's files"
            + (
                "; " + " and ".join(risks) + "."
                if risks
                else ", and nothing in it stands out as risky."
            ),
            "derived",
            (path, 0),
        )
    ]
    return {
        "novice": novice,
        "practitioner": practitioner,
        "principal": principal,
        "executive": executive,
    }


def _symbol_ladder(facts: Facts, sid: str) -> dict[str, list[dict[str, Any]]]:
    s = facts.symbols[sid]
    path = facts.path(sid)
    fid = s["file"]
    kind = {"class": "a class", "function": "a function", "method": "a method"}.get(
        s["kind"], s["kind"]
    )
    callers = sorted(facts.callers.get(sid, []), key=lambda e: (facts.path(e["s"]), e["line"]))
    callees = sorted(facts.callees.get(sid, []), key=lambda e: (facts.path(e["t"]), e["line"]))
    doc = first_sentence(s.get("doc", ""))
    args = parameters(s.get("signature") or "")
    novice = [
        _say(
            f"`{s['name']}` is {kind} in `{path}`, line {s['line']}.", "observed", (path, s["line"])
        )
    ]
    if doc:
        novice.append(_say(f"Its description says: “{doc}”", "observed", (path, s["line"])))
    if s["kind"] != "class":
        novice.append(
            _say(
                (
                    "It takes " + ", ".join(f"`{a}`" for a in args) + "."
                    if args
                    else "It takes no inputs."
                ),
                "observed",
                (path, s["line"]),
            )
        )
    novice.append(
        _say(
            f"It's used in {_plural(len(callers), 'place')} and calls "
            f"{_plural(len({e['t'] for e in callees}), 'other function')} from this project.",
            "derived",
            (path, s["line"]),
        )
    )
    practitioner = [_say(f"`{s.get('signature') or s['name']}`", "observed", (path, s["line"]))]
    if s.get("doc"):
        practitioner.append(_say(" ".join(s["doc"].split())[:600], "observed", (path, s["line"])))
    for e in callers[:10]:
        who = facts.symbols.get(e["s"], {}).get("name", e["s"])
        practitioner.append(
            _say(
                f"Called by `{who}` in `{facts.path(e['s'])}`.",
                "inferred" if e["o"] == "inferred" else "observed",
                (facts.path(e["s"]), e["line"]),
            )
        )
    for e in callees[:10]:
        practitioner.append(
            _say(
                f"Calls `{facts.symbols[e['t']]['name']}` in `{facts.path(e['t'])}`.",
                "inferred" if e["o"] == "inferred" else "observed",
                (path, e["line"]),
            )
        )
    for base in facts.bases.get(sid, []):
        practitioner.append(
            _say(
                f"Inherits from `{facts.symbols[base]['name']}` in `{facts.path(base)}`.",
                "observed",
                (path, s["line"]),
            )
        )
    total = len(facts.files)
    reach = facts.reach(fid)
    caller_files = {facts.symbols[e["s"]]["file"] for e in callers if e["s"] in facts.symbols}
    principal = [
        _say(
            f"Called from {_plural(len(caller_files), 'file')}; its file can reach {_plural(len(reach), 'file')} "
            f"({_share(len(reach), total)}) through imports.",
            "derived",
            (path, s["line"]),
        )
    ]
    complexity = facts.hotspots.get((path, s["name"]))
    if complexity:
        principal.append(
            _say(
                f"Cyclomatic complexity {complexity[0]}"
                + (": hard to change safely." if complexity[0] >= COMPLEX else "."),
                "derived",
                (path, complexity[1] or s["line"]),
            )
        )
    if fid in facts.in_cycle:
        principal.append(_say("Its file is in an import cycle.", "derived", (path, 0)))
    risky = bool(complexity and complexity[0] >= COMPLEX)
    executive = [
        _say(
            f"`{s['name']}` is used in {_plural(len(callers), 'place')} across {_plural(len(caller_files), 'file')}"
            + (
                "; it's complex enough that changes need careful review."
                if risky
                else "; nothing about it stands out as risky."
            ),
            "derived",
            (path, s["line"]),
        )
    ]
    return {
        "novice": novice,
        "practitioner": practitioner,
        "principal": principal,
        "executive": executive,
    }


def explain(
    model: dict[str, Any], focus: str, *, levels: tuple[str, ...] = LEVELS
) -> dict[str, Any]:
    """The ladder for one file or symbol, every statement with its evidence and basis."""
    unknown = [lvl for lvl in levels if lvl not in LEVELS]
    if unknown:
        raise ExplainError(f"unknown level {unknown[0]!r}; choose {', '.join(LEVELS)}")
    facts = Facts(model)
    target = facts.resolve(focus)
    ladder = _file_ladder(facts, target) if target in facts.files else _symbol_ladder(facts, target)
    return {
        "schema": SCHEMA,
        "project": model.get("project", {}).get("name", ""),
        "focus": target,
        "kind": "file" if target in facts.files else facts.symbols[target]["kind"],
        "path": facts.path(target),
        "levels": {lvl: ladder[lvl] for lvl in levels},
        "limitations": list(model.get("limitations", [])),
    }


def check_evidence(explanation: dict[str, Any], model: dict[str, Any]) -> list[str]:
    """Statements whose evidence doesn't point at a file in the model, or a line past its end (empty when sound)."""
    files = {f["path"]: f for f in model.get("files", [])}
    problems = []
    for level, statements in explanation["levels"].items():
        for st in statements:
            for ev in st["evidence"]:
                f = files.get(ev["path"])
                if f is None:
                    problems.append(f"{level}: {ev['path']} isn't in the model")
                elif (
                    ev["line"] and f["loc"] and ev["line"] > f["loc"] and f["path"].endswith(".py")
                ):
                    problems.append(
                        f"{level}: {ev['path']}:{ev['line']} is past the end of the file"
                    )
    return problems


