"""From a traced spec to a test-first plan, failing tests, verified evidence and a lock against drift.

* ``plan``: each requirement classified by what it states (behaviour, state, invariant, interface, security,
  performance), the tests that fit it, a risk from what its code reaches, and the tasks in dependency order
  (a requirement that names another, "after R1", depends on it). CAP-bdd-tdd-01/02, CAP-auto-sdd-02.
* ``skeletons``: a failing test per requirement that has none, named after its id, written before the code
  (CAP-bdd-tdd-03). Existing files are never overwritten.
* ``verify``: runs the tests that name each requirement, when asked, and calls a requirement done only when it is
  linked, has tests, and they pass (CAP-bdd-tdd-04).
* ``lock`` / ``drift``: the spec's requirements and the digest of each linked file, so a later trace shows what
  changed on either side before work starts (CAP-auto-sdd-04).

The classification reads the requirement's words with fixed rules; nothing is generated by a model.
"""

from __future__ import annotations

import hashlib
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

PLAN_SCHEMA = "dev-guru/spec-plan@1"
LOCK_SCHEMA = "dev-guru/spec-lock@1"
KINDS: dict[str, tuple[str, ...]] = {
    "invariant": (
        "never",
        "always",
        "must not",
        "at most",
        "at least",
        "unique",
        "no more than",
        "cannot",
        "only ever",
    ),
    "security": (
        "auth",
        "permission",
        "role",
        "secret",
        "token",
        "password",
        "encrypt",
        "login",
        "access",
    ),
    "performance": ("within", "seconds", "ms", "latency", "per second", "throughput", "fast"),
    "interface": (
        "api",
        "endpoint",
        "route",
        "request",
        "response",
        "http",
        "webhook",
        "returns",
        "status code",
    ),
    "state": (
        "status",
        "state",
        "store",
        "save",
        "persist",
        "record",
        "transition",
        "becomes",
        "history",
    ),
    "behaviour": (
        "when",
        "then",
        "given",
        "user",
        "can",
        "shows",
        "sends",
        "creates",
        "applies",
        "lets",
    ),
}
TESTS = {
    "invariant": ["property test over generated inputs", "a unit test of the boundary"],
    "security": [
        "negative tests: no token, wrong role, expired token",
        "a test that nothing secret is logged",
    ],
    "performance": ["a timing test with a stated budget, run outside the unit suite"],
    "interface": ["a contract test of the request and response", "error statuses (400/404/422)"],
    "state": [
        "unit tests of each transition",
        "an integration test that the state survives a reload",
    ],
    "behaviour": [
        "a BDD scenario (Given/When/Then) for the main path",
        "a unit test for each branch",
    ],
}
_REF = re.compile(
    r"\b(?:after|needs|requires|depends on|builds on|extends)\s+([A-Z][A-Z0-9]*-?\d+)", re.I
)


def classify(text: str) -> list[str]:
    low = f" {text.lower()} "
    found = [
        kind
        for kind, words in KINDS.items()
        if any(re.search(rf"\b{re.escape(w)}\b", low) for w in words)
    ]
    return found or ["behaviour"]


def plan(trace: dict[str, Any], model: dict[str, Any]) -> dict[str, Any]:
    from dev_guru.explain import Facts

    facts = Facts(model)
    total = max(1, len(facts.files))
    ids = {r["id"] for r in trace["requirements"]}
    items = []
    for r in trace["requirements"]:
        kinds = classify(r["text"])
        reach = 0
        for c in r.get("code", []):
            fid = (
                c["id"]
                if c["id"] in facts.files
                else (facts.symbols.get(c["id"]) or {}).get("file")
            )
            if fid:
                reach = max(reach, len(facts.reach(fid)))
        share = reach / total
        risk = (
            "high"
            if "security" in kinds or "invariant" in kinds or share >= 0.25
            else "medium"
            if r["status"] != "linked" or share >= 0.1 or "interface" in kinds
            else "low"
        )
        after = sorted({m.upper() for m in _REF.findall(r["text"])} & ids - {r["id"]})
        items.append(
            {
                "id": r["id"],
                "text": r["text"],
                "kinds": kinds,
                "risk": risk,
                "tests": [t for k in kinds for t in TESTS[k]],
                "has_tests": bool(r.get("tested")),
                "status": r["status"],
                "after": after,
                "reach": reach,
            }
        )
    order: list[dict[str, Any]] = []
    placed: set[str] = set()
    pending = list(items)
    while pending:  # dependencies first; a cycle is broken in document order and reported
        ready = [i for i in pending if set(i["after"]) <= placed] or [pending[0]]
        for i in ready:
            order.append(i)
            placed.add(i["id"])
            pending.remove(i)
    cycles = [
        i["id"] for i in order if not set(i["after"]) <= {o["id"] for o in order[: order.index(i)]}
    ]
    tasks = []
    for i in order:
        if not i["has_tests"]:
            tasks.append(
                {
                    "task": f"write a failing test for {i['id']}",
                    "requirement": i["id"],
                    "after": i["after"],
                }
            )
        if i["status"] != "linked":
            tasks.append(
                {
                    "task": f"implement {i['id']}, naming its code in the spec",
                    "requirement": i["id"],
                    "after": i["after"],
                }
            )
        tasks.append(
            {
                "task": f"make {i['id']}'s tests pass and verify",
                "requirement": i["id"],
                "after": i["after"],
            }
        )
    return {
        "schema": PLAN_SCHEMA,
        "spec": trace["spec"],
        "requirements": items,
        "tasks": tasks,
        "dependency_cycles": cycles,
    }


def plan_markdown(p: dict[str, Any]) -> str:
    lines = [
        f"# Test-first plan for {p['spec']}",
        "",
        "| Requirement | Kind | Risk | Tests to write | Has tests |",
        "|---|---|---|---|---|",
    ]
    for r in p["requirements"]:
        lines.append(
            f"| **{r['id']}** | {', '.join(r['kinds'])} | {r['risk']} | {'; '.join(r['tests'])} | {'yes' if r['has_tests'] else 'no'} |"
        )
    lines += ["", "## Tasks, in order", ""]
    lines += [
        f"{n}. {t['task']}" + (f" (after {', '.join(t['after'])})" if t["after"] else "")
        for n, t in enumerate(p["tasks"], 1)
    ]
    if p["dependency_cycles"]:
        lines += [
            "",
            f"Dependency cycle among {', '.join(p['dependency_cycles'])}: broken in document order.",
        ]
    return "\n".join(lines).replace("<", "&lt;") + "\n"


def skeletons(p: dict[str, Any], out_dir: Path, *, style: str = "pytest") -> list[Path]:
    """A failing test for each requirement without tests. Never overwrites a file."""
    written = []
    out_dir.mkdir(parents=True, exist_ok=True)
    for r in p["requirements"]:
        if r["has_tests"]:
            continue
        slug = re.sub(r"[^a-z0-9]+", "_", r["id"].lower()).strip("_")
        if style == "gherkin":
            target = out_dir / f"{slug}.feature"
            body = (
                f"Feature: {r['id']}\n  # {r['text']}\n\n  @{r['id']}\n  Scenario: {r['id']} holds\n"
                "    Given the system before the change\n    When the behaviour happens\n    Then the outcome is what the requirement states\n"
            )
        else:
            target = out_dir / f"test_{slug}.py"
            body = (
                f'"""{r["id"]}: {r["text"]}\n\nWritten before the code: it fails until {r["id"]} is implemented."""\n\nimport pytest\n\n\n'
                + "".join(
                    f'def test_{slug}_{n}():  # {r["id"]}: {t}\n    pytest.fail("{r["id"]} isn\'t implemented yet: {t}")\n\n\n'
                    for n, t in enumerate(r["tests"][:3], 1)
                )
            ).rstrip() + "\n"
        if target.exists():
            continue
        target.write_text(body, encoding="utf-8")
        written.append(target)
    return written


def verify(trace: dict[str, Any], root: Path, *, timeout: int = 600) -> dict[str, Any]:
    """Run the tests that name each requirement (Python files, with pytest) and record which pass."""
    results = []
    for r in trace["requirements"]:
        files = sorted({t["path"] for t in r.get("tested", []) if t["path"].endswith(".py")})
        if not files:
            results.append({"id": r["id"], "done": False, "why": "no test names it", "tests": []})
            continue
        argv = [
            sys.executable,
            "-m",
            "pytest",
            "-q",
            "-p",
            "no:cacheprovider",
            "-k",
            r["id"],
            *files,
        ]
        done = subprocess.run(  # noqa: S603 - this interpreter running pytest on the project's own tests, when asked
            argv, cwd=root, capture_output=True, text=True, timeout=timeout, check=False
        )
        tail = (done.stdout.strip().splitlines() or [""])[-1][:200]
        passed = done.returncode == 0
        ok = passed and r["status"] == "linked"
        why = (
            "linked, tested and passing"
            if ok
            else ("tests fail" if not passed else "tests pass, but no code is linked")
        )
        results.append(
            {
                "id": r["id"],
                "done": ok,
                "why": why,
                "tests": files,
                "result": tail,
                "exit": done.returncode,
            }
        )
    return {
        "spec": trace["spec"],
        "requirements": results,
        "done": sum(1 for x in results if x["done"]),
        "total": len(results),
    }


def _digest(path: Path) -> str | None:
    try:
        return "sha256:" + hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def lock(trace: dict[str, Any], root: Path) -> dict[str, Any]:
    files = sorted(
        {
            c["path"]
            for r in trace["requirements"]
            for c in r.get("code", [])
            if c.get("basis") == "observed"
        }
    )
    return {
        "schema": LOCK_SCHEMA,
        "spec": trace["spec"],
        "requirements": {
            r["id"]: hashlib.sha256(r["text"].encode()).hexdigest()[:16]
            for r in trace["requirements"]
        },
        "code": {f: _digest(root / f) for f in files},
    }


def drift(locked: dict[str, Any], trace: dict[str, Any], root: Path) -> dict[str, Any]:
    now = lock(trace, root)
    req_a, req_b = locked.get("requirements", {}), now["requirements"]
    changed_code = sorted(f for f, d in locked.get("code", {}).items() if _digest(root / f) != d)
    out: dict[str, Any] = {
        "added": sorted(set(req_b) - set(req_a)),
        "removed": sorted(set(req_a) - set(req_b)),
        "reworded": sorted(k for k in set(req_a) & set(req_b) if req_a[k] != req_b[k]),
        "code_changed": changed_code,
    }
    out["clean"] = not any(out.values())
    return out


